// Ahead-of-time Faust build: src/fx/faust/<id>.dsp -> src/fx/faust/build/<id>.{wasm,json}.
// The artifacts are committed, so the app never ships the libfaust compiler.
//
// Needs @grame/faustwasm (LGPL-2.1, ~34 MB). It is not an app dependency; point
// FAUSTWASM_DIR at an install of it (e.g. `npm install @grame/faustwasm` in any folder):
//   FAUSTWASM_DIR=/path/to/node_modules/@grame/faustwasm node scripts/build-faust.mjs [ids...]
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.resolve(here, '../src/fx/faust');
const outDir = path.join(srcDir, 'build');
const fwDir = process.env.FAUSTWASM_DIR;
if (!fwDir) {
  console.error('Set FAUSTWASM_DIR to an @grame/faustwasm install (see the header of this script).');
  process.exit(1);
}
const { default: faust2wasmFiles } = await import(pathToFileURL(path.join(fwDir, 'src/faust2wasmFiles.js')).href);

const ids = process.argv.slice(2).length ? process.argv.slice(2) : fs.readdirSync(srcDir).filter((f) => f.endsWith('.dsp')).map((f) => f.replace(/\.dsp$/, ''));
fs.mkdirSync(outDir, { recursive: true });
for (const id of ids) {
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), `faust-${id}-`));
  // -ftz 2 (flush denormals) is added by faust2wasmFiles; single precision, internal memory (wasm-i)
  await faust2wasmFiles(path.join(srcDir, `${id}.dsp`), tmp, [], false);
  const meta = JSON.parse(fs.readFileSync(path.join(tmp, 'dsp-meta.json'), 'utf8'));
  delete meta.library_list; // host paths, not needed at runtime
  delete meta.include_pathnames;
  fs.copyFileSync(path.join(tmp, 'dsp-module.wasm'), path.join(outDir, `${id}.wasm`));
  fs.writeFileSync(path.join(outDir, `${id}.json`), JSON.stringify(meta, null, 1) + '\n');
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`built ${id}: ${fs.statSync(path.join(outDir, `${id}.wasm`)).size} bytes, ${meta.inputs} in / ${meta.outputs} out`);
}

// base64 copies in one TS module: no fetch of a .wasm file (works in Vite dev/build, Electron file://, vitest)
const all = fs.readdirSync(outDir).filter((f) => f.endsWith('.wasm')).sort();
const lines = all.map((f) => `  ${f.replace(/\.wasm$/, '')}: '${fs.readFileSync(path.join(outDir, f)).toString('base64')}',`);
fs.writeFileSync(
  path.join(outDir, 'wasm.ts'),
  `// Generated by scripts/build-faust.mjs from src/fx/faust/*.dsp. Do not edit.\nexport const FAUST_WASM_BASE64: Record<string, string> = {\n${lines.join('\n')}\n};\n`,
);
